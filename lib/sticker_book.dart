import 'package:flutter/painting.dart';

/// A sheet of stickers, like a real sticker book page: the sheet image as
/// it was generated, and each sticker cut out of it with where it sits.
class StickerSheet {
  final String id, label, sheet;
  /// Width / height of the sheet.
  final double aspect;
  final List<SheetSticker> stickers;
  const StickerSheet(this.id, this.label, this.sheet, this.aspect, this.stickers);
}

class SheetSticker {
  final String asset;
  /// Where the sticker sits on its sheet, as fractions of the sheet.
  final Rect rect;
  const SheetSticker(this.asset, this.rect);
}

